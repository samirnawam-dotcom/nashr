import { Page, textWidth, wrap } from './pdf.js'

/* The PDF of one stored document (SPEC 11.2): what the printable page in the app shows, in English. */

export type DocView = { type: string; number: string; dealRef: string | null; relatedNumber: string | null; onBehalf: boolean; taxDocument: boolean
  issuer: { name: string; trn: string | null; address: string | null }; recipient: { name: string; trn: string | null; address: string | null }
  items: { description: string; amount?: number; quantity?: number; unitPrice?: number; paymentRef?: string }[]; note: string | null
  currency: string; subtotal: number; vatBp: number; vat: number; total: number; issuedAt: Date | string }

const TITLE: Record<string, string> = { order: 'Order', receipt: 'Payment receipt', credit_note: 'Credit note' }
export const titleOf = (d: Pick<DocView, 'type' | 'taxDocument'>) =>
  d.type === 'media_invoice' || d.type === 'commission_invoice' ? (d.taxDocument ? 'Tax invoice' : 'Invoice') : TITLE[d.type] ?? d.type
const amount = (fils: number, currency: string) => `${currency} ${(fils / 100).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
const dubaiDate = (at: Date | string) => new Date(at).toLocaleDateString('en-GB', { timeZone: 'Asia/Dubai', day: 'numeric', month: 'long', year: 'numeric' })

export function documentPdf(d: DocView) {
  const p = new Page(), L = 50, R = p.width - 50, W = R - L
  let y = 64
  // Heading: what it is and its number, then when and for which order.
  p.text('Nashr', L, y - 22, 9, 'B', 0.45)
  const title = titleOf(d)
  p.text(title, L, y, 22, 'B')
  p.right(d.number, R, y, 12, 'B')
  y += 20
  const meta = [`Issued ${dubaiDate(d.issuedAt)}`, d.dealRef && `Order ${d.dealRef}`, d.relatedNumber && `Credits ${d.relatedNumber}`].filter(Boolean).join('   ·   ')
  p.text(meta, L, y, 9.5, 'R', 0.35)
  y += 16; p.rule(L, y, R, 0.75, 0.75); y += 24

  // The two parties side by side.
  const col = (W - 30) / 2
  const party = (label: string, x: number, who: DocView['issuer'], extra?: string) => {
    let yy = y
    p.text(label, x, yy, 8.5, 'B', 0.45); yy += 15
    for (const line of wrap(who.name, col, 11, 'B')) { p.text(line, x, yy, 11, 'B'); yy += 14 }
    for (const line of (who.address ?? '').split('\n').flatMap(l => wrap(l, col, 9.5)).filter(Boolean)) { p.text(line, x, yy, 9.5, 'R', 0.2); yy += 12.5 }
    if (who.trn) { p.text(`TRN ${who.trn}`, x, yy, 9.5, 'R', 0.2); yy += 12.5 }
    if (extra) for (const line of wrap(extra, col, 8.5)) { p.text(line, x, yy, 8.5, 'R', 0.45); yy += 11 }
    return yy
  }
  y = Math.max(party('FROM', L, d.issuer, d.onBehalf ? "Issued by Nashr on the publisher's behalf" : undefined), party('TO', L + col + 30, d.recipient)) + 20

  // The lines.
  p.box(L, y - 13, W, 20); p.text('Description', L + 8, y, 9, 'B', 0.3); p.right('Amount', R - 8, y, 9, 'B', 0.3); y += 22
  for (const i of d.items) {
    const value = i.amount ?? (i.unitPrice ?? 0) * (i.quantity ?? 1)
    const lines = wrap(i.description + (i.paymentRef ? ` (payment ${i.paymentRef})` : ''), W - 140, 10)
    lines.forEach((line, n) => p.text(line, L + 8, y + n * 13, 10))
    p.right(amount(value, d.currency), R - 8, y, 10)
    y += lines.length * 13 + 6; p.rule(L, y - 2, R); y += 14
  }

  // Totals, right-aligned.
  const sum = (label: string, value: number, bold = false) => {
    const face = bold ? 'B' : 'R', size = bold ? 11.5 : 10
    p.text(label, R - 230, y, size, face, bold ? 0 : 0.3); p.right(amount(value, d.currency), R - 8, y, size, face); y += bold ? 20 : 16
  }
  y += 4
  sum('Subtotal', d.subtotal)
  if (d.taxDocument || d.vat > 0) sum(`VAT ${d.vatBp / 100}%`, d.vat)
  p.rule(R - 230, y - 10, R, 0.75, 0.5); y += 4
  sum('Total', d.total, true)

  // Notes, then what the document is and is not.
  y += 16
  const notes = [d.note, d.type === 'receipt' ? "Payment received by Nashr on behalf of the publisher. This is not a tax invoice; the publisher's tax invoice is issued separately." : null]
  for (const n of notes.filter(Boolean) as string[]) for (const line of wrap(n, W, 9)) { p.text(line, L, y, 9, 'R', 0.35); y += 12 }
  const foot = 'Generated by Nashr from the stored document record. Amounts in ' + d.currency + '.'
  p.text(foot, (p.width - textWidth(foot, 7.5)) / 2, p.height - 30, 7.5, 'R', 0.55)
  return p.pdf(`${title} ${d.number}`)
}

import { Page, textWidth, wrap } from './pdf.js'
import { AR } from '../../web/src/i18n-ar.js'
import { arabicFor } from '../../web/src/server-text.js'

/*
 * The PDF of one stored document (SPEC 11.2): what the printable page in the app shows, in English or in Arabic.
 * The Arabic comes from the app's own dictionaries (the same words the screens use), and the page is mirrored:
 * it reads from the right, with the issuer on the right and amounts on the left.
 */

export type Lang = 'en' | 'ar'
export type DocView = { type: string; number: string; dealRef: string | null; relatedNumber: string | null; onBehalf: boolean; taxDocument: boolean
  issuer: { name: string; trn: string | null; address: string | null }; recipient: { name: string; trn: string | null; address: string | null }
  items: { description: string; amount?: number; quantity?: number; unitPrice?: number; paymentRef?: string }[]; note: string | null
  currency: string; subtotal: number; vatBp: number; vat: number; total: number; issuedAt: Date | string }

const TITLE: Record<string, string> = { order: 'Order', receipt: 'Payment receipt', credit_note: 'Credit note' }
export const titleOf = (d: Pick<DocView, 'type' | 'taxDocument'>) =>
  d.type === 'media_invoice' || d.type === 'commission_invoice' ? (d.taxDocument ? 'Tax invoice' : 'Invoice') : TITLE[d.type] ?? d.type

// Words only the PDF needs, or where the PDF needs a different word from the screens ("From" there is a date).
const PDF_AR: Record<string, string> = {
  FROM: 'من', TO: 'إلى', Order: 'طلب حجز', '(payment {ref})': '(الدفعة {ref})',
  'Generated by Nashr from the stored document record. Amounts in {currency}.': 'أنشأتها نشر من سجل المستند المحفوظ. المبالغ بعملة {currency}.',
}

export function documentPdf(d: DocView, lang: Lang = 'en') {
  const ar = lang === 'ar'
  // a label in the document's language: the PDF's own words first, then the app's dictionary
  const L = (en: string, vars: Record<string, string | number> = {}) =>
    (ar ? PDF_AR[en] ?? AR[en] ?? en : en).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
  const said = (text: string) => ar ? arabicFor(text) : text // what the server wrote (notes, lines)
  const amount = (fils: number, currency: string) => {
    const n = (fils / 100).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    return ar ? `${n} ${currency === 'AED' ? 'درهم' : currency}` : `${currency} ${n}`
  }
  const day = (at: Date | string) => new Date(at).toLocaleDateString(ar ? 'ar-AE-u-nu-latn' : 'en-GB', { timeZone: 'Asia/Dubai', day: 'numeric', month: 'long', year: 'numeric' })

  const p = new Page(), M = 50, W = p.width - 2 * M
  // Positions are measured from the page's starting edge: the left in English, the right in Arabic.
  const lead = (s: string, x: number, y: number, size = 10, face: 'R' | 'B' = 'R', grey = 0) =>
    ar ? p.right(s, p.width - x, y, size, face, grey, true) : p.text(s, x, y, size, face, grey)
  const trail = (s: string, x: number, y: number, size = 10, face: 'R' | 'B' = 'R', grey = 0) =>
    ar ? p.text(s, p.width - x, y, size, face, grey, true) : p.right(s, x, y, size, face, grey)
  const rule = (x1: number, y: number, x2: number, weight?: number, grey?: number) => ar ? p.rule(p.width - x2, y, p.width - x1, weight, grey) : p.rule(x1, y, x2, weight, grey)
  const box = (x: number, y: number, w: number, h: number) => p.box(ar ? p.width - x - w : x, y, w, h)
  const L0 = M, R0 = p.width - M

  let y = 64
  // Heading: what it is and its number, then when and for which order.
  lead(ar ? 'نشر' : 'Nashr', L0, y - 22, 9, 'B', 0.45)
  const title = L(titleOf(d))
  lead(title, L0, y, 22, 'B')
  trail(d.number, R0, y, 12, 'B')
  y += 20
  const meta = [L('Issued {date}', { date: day(d.issuedAt) }), d.dealRef && L('Order {ref}', { ref: d.dealRef }), d.relatedNumber && L('Credits {ref}', { ref: d.relatedNumber })]
    .filter(Boolean).join('   ·   ')
  lead(meta, L0, y, 9.5, 'R', 0.35)
  y += 16; rule(L0, y, R0, 0.75, 0.75); y += 24

  // The two parties side by side: the issuer first, on the starting side.
  const col = (W - 30) / 2
  const party = (label: string, x: number, who: DocView['issuer'], extra?: string) => {
    let yy = y
    lead(L(label), x, yy, 8.5, 'B', 0.45); yy += 15
    for (const line of wrap(who.name, col, 11, 'B')) { lead(line, x, yy, 11, 'B'); yy += 14 }
    for (const line of (who.address ?? '').split('\n').flatMap(l => wrap(l, col, 9.5)).filter(Boolean)) { lead(line, x, yy, 9.5, 'R', 0.2); yy += 12.5 }
    if (who.trn) { lead(`${L('TRN')} ${who.trn}`, x, yy, 9.5, 'R', 0.2); yy += 12.5 }
    if (extra) for (const line of wrap(extra, col, 8.5)) { lead(line, x, yy, 8.5, 'R', 0.45); yy += 11 }
    return yy
  }
  y = Math.max(party('FROM', L0, d.issuer, d.onBehalf ? L("Issued by Nashr on the publisher's behalf") : undefined), party('TO', L0 + col + 30, d.recipient)) + 20

  // The lines.
  box(L0, y - 13, W, 20); lead(L('Description'), L0 + 8, y, 9, 'B', 0.3); trail(L('Amount'), R0 - 8, y, 9, 'B', 0.3); y += 22
  for (const i of d.items) {
    const value = i.amount ?? (i.unitPrice ?? 0) * (i.quantity ?? 1)
    const lines = wrap(said(i.description) + (i.paymentRef ? ` ${L('(payment {ref})', { ref: i.paymentRef })}` : ''), W - 140, 10)
    lines.forEach((line, n) => lead(line, L0 + 8, y + n * 13, 10))
    trail(amount(value, d.currency), R0 - 8, y, 10)
    y += lines.length * 13 + 6; rule(L0, y - 2, R0); y += 14
  }

  // Totals, on the closing side.
  const sum = (label: string, value: number, bold = false) => {
    const face = bold ? 'B' : 'R', size = bold ? 11.5 : 10
    lead(label, R0 - 230, y, size, face, bold ? 0 : 0.3); trail(amount(value, d.currency), R0 - 8, y, size, face); y += bold ? 20 : 16
  }
  y += 4
  sum(L('Subtotal'), d.subtotal)
  if (d.taxDocument || d.vat > 0) sum(L('VAT {rate}%', { rate: d.vatBp / 100 }), d.vat)
  rule(R0 - 230, y - 10, R0, 0.75, 0.5); y += 4
  sum(L('Total'), d.total, true)

  // Notes, then what the document is and is not.
  y += 16
  const receiptNote = "Payment received by Nashr on behalf of the publisher. This is not a tax invoice; the publisher's tax invoice is issued separately."
  const notes = [d.note && said(d.note), d.type === 'receipt' ? L(receiptNote) : null]
  for (const n of notes.filter(Boolean) as string[]) for (const line of wrap(n, W, 9)) { lead(line, L0, y, 9, 'R', 0.35); y += 12 }
  const foot = L('Generated by Nashr from the stored document record. Amounts in {currency}.', { currency: d.currency })
  p.text(foot, (p.width - textWidth(foot, 7.5)) / 2, p.height - 30, 7.5, 'R', 0.55, ar)
  return p.pdf(`${title} ${d.number}`)
}
